import '../../domain/entities/user.dart';

class UserModel extends User {
  const UserModel({
    super.id,
    super.firstname,
    super.lastname,
    super.username,
    super.email,
    super.dialCode,
    super.mobile,
    super.refBy,
    super.image,
    super.countryName,
    super.countryCode,
    super.city,
    super.state,
    super.zip,
    super.address,
    super.late,
    super.lang,
    super.status,
    super.kycRejectionReason,
    super.kv,
    super.ev,
    super.sv,
    super.profileComplete,
    super.verCodeSendAt,
    super.ts,
    super.tv,
    super.tsc,
    super.banReason,
    super.provider,
    super.providerId,
    super.createdAt,
    super.updatedAt,
    super.profileImage,
    super.idFront,
    super.idBack,
    super.licence,
    super.otherFile,
    super.media,
    super.token,
  });

  factory UserModel.fromJson(Map<String, dynamic> json) {
    final data = json['data'] ?? {};
    return UserModel(
      id: data['id'],
      firstname: data['firstname'],
      lastname: data['lastname'],
      username: data['username'],
      email: data['email'],
      dialCode: data['dial_code'],
      mobile: data['mobile'],
      refBy: data['ref_by'],
      image: data['image'],
      countryName: data['country_name'],
      countryCode: data['country_code'],
      city: data['city'],
      state: data['state'],
      zip: data['zip'],
      address: data['address'],
      late: data['late'],
      lang: data['lang'],
      status: data['status'],
      kycRejectionReason: data['kyc_rejection_reason'],
      kv: data['kv'],
      ev: data['ev'],
      sv: data['sv'],
      profileComplete: data['profile_complete'],
      verCodeSendAt: data['ver_code_send_at'],
      ts: data['ts'],
      tv: data['tv'],
      tsc: data['tsc'],
      banReason: data['ban_reason'],
      provider: data['provider'],
      providerId: data['provider_id'],
      createdAt: data['created_at'],
      updatedAt: data['updated_at'],
      profileImage: data['profile_image'],
      idFront: data['id_front'],
      idBack: data['id_back'],
      licence: data['licence'],
      otherFile: data['other_file'],
      media: data['media'],
      token: json['token'],
    );
  }
}
